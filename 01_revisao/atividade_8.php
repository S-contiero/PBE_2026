<?php

$numero1 = 15;
$numero2 = 5;
$operacao = "+";

switch ($operacao) {

    case "+":
        echo $numero1 + $numero2;
        break;

    case "-":
        echo $numero1 - $numero2;
        break;

    case "*":
        echo $numero1 * $numero2;
        break;

    case "/":
        echo $numero1 / $numero2;
        break;
}

?>
